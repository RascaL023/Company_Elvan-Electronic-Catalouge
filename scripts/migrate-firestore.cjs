/**
 * Copy Firestore data (products, categories, brands) from the OLD Firebase
 * project to a NEW one while preserving document IDs.
 *
 * For products, `imageFileIds` are remapped to the NEW ImageKit account's
 * fileIds using scripts/imagekit-fileid-map.json (produced by
 * migrate-imagekit-to-imagekit.cjs). If a key has no mapping, its fileId is
 * set to '' (matching the legacy behavior where the image can't be auto-deleted).
 *
 * Usage:
 *   node scripts/migrate-firestore.cjs
 *
 * Requires:
 *   - scripts/service-account.json     (OLD project admin SDK key)
 *   - scripts/service-account-new.json (NEW project admin SDK key)
 *   - scripts/imagekit-fileid-map.json (optional; generated by the image script)
 *
 * The `images` field is copied unchanged because the relative keys are the same
 * across ImageKit accounts (migrated to identical folder/file layout).
 */

const fs = require('fs');
const path = require('path');

const OLD_SA_PATH = path.join(__dirname, 'service-account.json');
const NEW_SA_PATH = path.join(__dirname, 'service-account-new.json');
const MAP_PATH = path.join(__dirname, 'imagekit-fileid-map.json');

for (const [label, p] of [['service-account.json (OLD)', OLD_SA_PATH], ['service-account-new.json (NEW)', NEW_SA_PATH]]) {
  if (!fs.existsSync(p)) {
    console.error(`❌ ${label} tidak ditemukan di ${p}`);
    process.exit(1);
  }
}

const { initializeApp, cert } = require('firebase-admin/app');
const { getFirestore } = require('firebase-admin/firestore');

const oldAccount = require(OLD_SA_PATH);
const newAccount = require(NEW_SA_PATH);

const oldApp = initializeApp(
  { credential: cert(oldAccount) },
  'old-project'
);
const newApp = initializeApp(
  { credential: cert(newAccount) },
  'new-project'
);

const oldDb = getFirestore(oldApp); // old one usually is (default)
const newDb = getFirestore(newApp, 'default'); // new one is explicitly 'default'

const COLLECTIONS = ['products', 'categories', 'brands'];

// Load key -> newFileId mapping if present.
let fileIdMap = {};
if (fs.existsSync(MAP_PATH)) {
  fileIdMap = JSON.parse(fs.readFileSync(MAP_PATH, 'utf8'));
  console.log(`📦 Mapping fileId dimuat: ${Object.keys(fileIdMap).length} entri (${MAP_PATH})`);
} else {
  console.log(`⚠️  ${MAP_PATH} tidak ada — imageFileIds TIDAK akan di-remap.`);
}

function remapImageFileIds(productData) {
  // Only touch imageFileIds when the field already exists, so legacy docs
  // (without it) keep their original shape.
  if (!Array.isArray(productData.imageFileIds)) return productData;
  const images = productData.images || [];
  const newFileIds = images.map((key) => fileIdMap[key] ?? '');
  return { ...productData, imageFileIds: newFileIds };
}

async function copyCollection(name) {
  const snapshot = await oldDb.collection(name).get();
  console.log(`\nCollection "${name}": ${snapshot.size} dokumen.`);
  let written = 0;
  let skipped = 0;

  for (const doc of snapshot.docs) {
    let data = doc.data();

    if (name === 'products') {
      data = remapImageFileIds(data);
    }

    const existing = await newDb.collection(name).doc(doc.id).get();
    if (existing.exists) {
      console.log(`  ≫ ${doc.id}: sudah ada di project baru (dilewati)`);
      skipped++;
      continue;
    }

    await newDb.collection(name).doc(doc.id).set(data);
    written++;
    console.log(`  ✓ ${doc.id}`);
  }

  console.log(`  → ${written} ditulis, ${skipped} dilewati (sudah ada).`);
  return { written, skipped };
}

async function main() {
  console.log(`OLD project: ${oldAccount.project_id}`);
  console.log(`NEW project: ${newAccount.project_id}\n`);

  const summary = {};
  for (const name of COLLECTIONS) {
    summary[name] = await copyCollection(name);
  }

  console.log('\n✅ Migrasi Firestore selesai.');
  console.log('Ringkasan:');
  for (const [name, s] of Object.entries(summary)) {
    console.log(`  ${name}: ${s.written} ditulis, ${s.skipped} dilewati`);
  }

  await oldApp.delete();
  await newApp.delete();
}

main().catch((err) => {
  console.error('Migrasi gagal:', err);
  process.exit(1);
});
